"""``softsim fit``: any observable of any scenario against a registered measured table. A twin experiment:
the "measurement" is a run at a hidden modulus (plus noise), so the recovered value can be checked."""

from pathlib import Path

import numpy as np
import pandas as pd
import pytest
import yaml

from softsim.errors import ConfigError

pytest.importorskip("gmsh")
pytest.importorskip("mujoco")

SPHERE = Path(__file__).parents[1] / "scenarios" / "inflation" / "hollow_sphere.yaml"
E = "body.material.elastic.youngs_modulus"
RAMP = "actuators[0].schedule=[[0, 0], [0.03, 2000], [0.04, 2000]]"
BASE = ["body.mesh.size=7mm", "simulation.duration=0.04", "simulation.timestep=0.0002", RAMP, "output.save_model=false"]


def _measure(tmp_path, hidden=45e3, noise=0.0, seed=0):
    """The cavity's pressure-volume curve of the sphere at E = ``hidden``, sampled at 21 pressures (kPa, mm^3)."""
    from softsim.runner import run_config

    ts = run_config(SPHERE, [*BASE, f"{E}={hidden}"]).timeseries
    up = ts[ts.t <= 0.03]
    p = np.linspace(0, 2000, 21)
    v = np.interp(p, up.cavity_pressure, up.cavity_volume)
    v = v + np.random.default_rng(seed).normal(0, noise * (v.max() - v.min()), len(v))
    path = tmp_path / "pv.csv"
    pd.DataFrame({"p_kPa": p / 1e3, "volume_mm3": v * 1e9, "run": 1}).to_csv(path, index=False)
    return path


def _spec(tmp_path, table, **data):
    spec = {"config": str(SPHERE), "backend": "mujoco", "overrides": BASE,
            "data": {"source": {"name": "synthetic twin experiment", "doi": "none (generated by the test)",
                                "licence": "n/a", "file": str(table)},
                     "kind": "curve", "x": {"column": "p_kPa", "scale": 1000, "sim": "cavity_pressure"},
                     "y": {"column": "volume_mm3", "scale": 1e-9, "sim": "cavity_volume"}, **data},
            "parameters": {E: {"initial": "25 kPa", "bounds": ["10 kPa", "100 kPa"], "log": True}},
            "checks": {}, "max_evaluations": 14, "output": str(tmp_path / "out")}
    path = tmp_path / "fit.yaml"
    path.write_text(yaml.safe_dump(spec))
    return path


def test_fit_recovers_the_hidden_modulus(tmp_path):
    """A noiseless curve gives back the hidden E (45 kPa) to 1% (measured 0.4%); with 1% noise (of the range) to 6%
    (measured 3.5%, the volume goes as 1/E so noise maps one to one), and the report states the source and
    the card is effective (MuJoCo)."""
    from softsim.experiments.fit import Fit

    report = Fit(_spec(tmp_path, _measure(tmp_path))).run()
    assert report["best"][E] == pytest.approx(45e3, rel=0.01)
    assert report["cost"] < 0.01 < report["raw_card_cost"] and report["noise_floor"] == 0.0
    assert report["source"]["doi"].startswith("none") and report["rows"] == 21
    card = yaml.safe_load(Path(report["material_file"]).read_text())
    assert card["kind"] == "effective" and "measured data (synthetic twin experiment" in card["source"]
    assert len(Fit(tmp_path / "fit.yaml").history) == report["evaluations"]  # resumable
    noisy = tmp_path / "noisy"
    noisy.mkdir()
    report = Fit(_spec(noisy, _measure(noisy, noise=0.01, seed=3))).run()
    assert report["best"][E] == pytest.approx(45e3, rel=0.06)
    assert 0.005 < report["cost"] < 0.03


def test_fit_validation_and_noise_floor(tmp_path):
    from softsim.experiments.fit import Fit

    table = _measure(tmp_path)
    for broken, match in (({"source": {"name": "x"}}, "doi|licence|file"), ({"kind": "points"}, "curve or series"),
                          ({"x": {"column": "nope", "scale": 1, "sim": "cavity_pressure"}}, "no column"),
                          ({"filter": {"run": 2}}, "fewer than 3 rows"), ({"relative_to": "mean"}, "first or none")):
        with pytest.raises(ConfigError, match=match):
            Fit(_spec(tmp_path, table, **broken))
    # repeated x: the scatter about the mean at each x is the floor
    df = pd.read_csv(table)
    twice = pd.concat([df, df.assign(volume_mm3=df.volume_mm3 * 1.02)])
    twice.to_csv(table, index=False)
    fit = Fit(_spec(tmp_path, table))
    v = df.volume_mm3.to_numpy()
    expected = 0.01 * np.sqrt(np.mean(v**2)) / (1.02 * v.max() - v[0])  # pairs a, 1.02 a scatter by 1% of a
    assert fit.noise_floor() == pytest.approx(expected, rel=1e-6)


def test_fit_series_kind(tmp_path):
    """A time series y(t) is compared at the measured times; a wrong modulus costs more than the right one."""
    from softsim.experiments.fit import Fit
    from softsim.runner import run_config

    ts = run_config(SPHERE, [*BASE, f"{E}=45e3"]).timeseries
    sel = ts.iloc[::5]
    path = tmp_path / "series.csv"
    pd.DataFrame({"t_s": sel.t, "volume_mm3": sel.cavity_volume * 1e9}).to_csv(path, index=False)
    spec = yaml.safe_load(_spec(tmp_path, path).read_text())
    spec["data"].update(kind="series", t={"column": "t_s", "scale": 1})
    spec["data"].pop("x")
    (tmp_path / "series.yaml").write_text(yaml.safe_dump(spec))
    fit = Fit(tmp_path / "series.yaml")
    right, wrong = fit.errors([], {E: 45e3})["cost"], fit.errors([], {E: 30e3})["cost"]
    assert right < 0.005 and wrong > 10 * right


def test_curve_uses_the_loading_branch(tmp_path):
    """Against a run that loads and unloads along different paths (viscoelastic, or a leaking actuator), the
    measured curve is compared with the loading branch only. Mutant: the whole run (the unloading values,
    overwriting the loading ones at the same x, would be used)."""
    from softsim.experiments.fit import Fit

    fit = Fit(_spec(tmp_path, _measure(tmp_path)))
    x = np.r_[np.linspace(0, 2000, 11), np.linspace(2000, 0, 11)[1:]]
    y = np.r_[np.linspace(0, 1.0, 11), np.linspace(1.0, 0.5, 11)[1:]] * 1e-6  # unloads 0.5 up at x = 0
    sim = pd.DataFrame({"t": np.arange(len(x)) * 1e-3, "cavity_pressure": x, "cavity_volume": y})
    got = fit.simulated(sim)
    np.testing.assert_allclose(got, np.interp(fit.table["x"], x[:11], y[:11]), atol=1e-15)
